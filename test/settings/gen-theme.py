#!/usr/bin/env python3
"""gen-theme.py DUMP.json OUT.py: the settings app's generated theme values (theme_gen.py)
from design-dump.js's output. Every var(--il-NAME[,fallback]) is resolved against the
voice's E-ink tokens (white/editorial: eink, stationery: stationery-eink). Only the
E-ink scheme is used: no colour palettes, no paper/night."""
import json
import pprint
import re
import sys

VAR = re.compile(r"var\(--il-([a-z-]+)(?:,((?:[^()]|\([^()]*\))*))?\)")


def resolve(v, il):
    if isinstance(v, str):
        for _ in range(4):
            n = VAR.sub(lambda m: il.get("--il-" + m.group(1)) or (m.group(2) or "").strip(), v)
            if n == v:
                break
            v = n
        return v
    if isinstance(v, list):
        return [resolve(x, il) for x in v]
    return v


def main(src, out):
    d = json.load(open(src))
    gen = {}
    for voice, x in d.items():
        il = x["il"]
        gen[voice] = {
            "il": {k[5:]: v for k, v in il.items() if k.startswith("--il-")},
            "t": {k: resolve(v, il) for k, v in x["t"].items() if k != "ilv"},
            "k": {k: resolve(v, il) for k, v in x["k"].items()},
        }
    with open(out, "w") as f:
        f.write('"""GENERATED by test/settings/gen-theme.py from the design\n'
                '(design "E-ink Shell", E-ink scheme): do not edit by hand;\n'
                'theme.py maps these onto the keys the app draws with."""\n\nGEN = ')
        f.write(pprint.pformat(gen, width=110, sort_dicts=True))
        f.write("\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
