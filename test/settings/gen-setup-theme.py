#!/usr/bin/env python3
"""gen-setup-theme.py DUMP.json OUT.py: glassine-setup's generated theme values from
setup-dump.js's output, every var(--il-NAME[,fallback]) resolved against the voice's
E-ink tokens (as gen-theme.py does for glassine-settings). E-ink scheme only."""
import json
import pprint
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from importlib import import_module  # noqa: E402

_resolve = import_module("gen-theme").resolve


def resolve(v, il):
    if isinstance(v, dict):
        return {k: resolve(x, il) for k, x in v.items()}
    return _resolve(v, il)


def main(src, out):
    d = json.load(open(src))
    gen = {}
    for voice in ("white", "editorial", "stationery"):
        il = d[voice]["il"]
        gen[voice] = {"il": {k[5:]: v for k, v in il.items() if k.startswith("--il-")},
                      "k": {k: resolve(v, il) for k, v in d[voice]["k"].items()}}
    with open(out, "w") as f:
        f.write('"""GENERATED by test/settings/gen-setup-theme.py from the design\n'
                '(design "E-ink Shell", EinkSetup, E-ink scheme): do not edit by hand."""\n\nGEN = ')
        f.write(pprint.pformat(gen, width=120, sort_dicts=True))
        f.write("\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
